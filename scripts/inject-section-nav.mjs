// Adds (or refreshes) the category section bar on the main site's pages.
//
// index.html / feed.html / archive.html are hand-authored by Claude every
// morning, so anything added to them by hand would be silently dropped on the
// next edition. This script is idempotent and re-runnable: it replaces the
// block between the SECTION-NAV markers if present, inserts it after the
// primary <nav> if not. daily.yml runs it after Claude's step, so the bar
// heals itself even when a day's rewrite drops it.
//
//   node scripts/inject-section-nav.mjs            # all three main pages
//   node scripts/inject-section-nav.mjs index.html # just one

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const SECTIONS = [
  { slug: "quiet-kindness", name: "Quiet Kindness" },
  { slug: "small-wonders", name: "Small Wonders" },
  { slug: "everyday-joy", name: "Everyday Joy" },
  { slug: "nature", name: "Nature" },
  { slug: "science-medicine", name: "Science & Medicine" },
  { slug: "global-progress", name: "Global Progress" },
  { slug: "coming-together", name: "Coming Together" },
  { slug: "open-hands", name: "Open Hands" },
  { slug: "human-spirit", name: "Human Spirit" },
];

const START = "<!-- SECTION-NAV:START (generated by scripts/inject-section-nav.mjs — do not hand-edit) -->";
const END = "<!-- SECTION-NAV:END -->";

const CSS_START = "/* SECTION-NAV-CSS:START */";
const CSS_END = "/* SECTION-NAV-CSS:END */";

const CSS = `${CSS_START}
.section-nav {
  border-top: 1px solid var(--rule-soft);
  border-bottom: 1px solid var(--rule-soft);
  padding: 12px var(--gutter);
}
.section-nav-inner {
  max-width: 1240px; margin: 0 auto;
  display: flex; flex-wrap: wrap; gap: 6px 22px; align-items: baseline;
  font-family: var(--sans); font-size: 11px; letter-spacing: 0.14em;
  text-transform: uppercase;
}
.section-nav .label { color: var(--ink-mute); margin-right: 4px; }
.section-nav a { text-decoration: none; color: var(--ink-soft); }
.section-nav a:hover { color: var(--accent-deep); }
${CSS_END}`;

const navHtml = () => {
  const links = SECTIONS.map(
    (s) => `      <a href="editions/${s.slug}/index.html">${s.name.replace(/&/g, "&amp;")}</a>`
  ).join("\n");
  return `${START}
  <nav class="section-nav" aria-label="Sections">
    <div class="section-nav-inner">
      <span class="label">Sections</span>
${links}
    </div>
  </nav>
  ${END}`;
};

function upsertBlock(src, startMarker, endMarker, block, insertAfterRegex) {
  const s = src.indexOf(startMarker);
  const e = src.indexOf(endMarker);
  if (s !== -1 && e !== -1) {
    return src.slice(0, s) + block + src.slice(e + endMarker.length);
  }
  const m = src.match(insertAfterRegex);
  if (!m) return null;
  const at = m.index + m[0].length;
  return src.slice(0, at) + "\n  " + block + src.slice(at);
}

const files = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ["index.html", "feed.html", "archive.html"];

let changed = 0;
for (const file of files) {
  const p = path.join(ROOT, file);
  let html;
  try {
    html = await fs.readFile(p, "utf8");
  } catch {
    console.log(`skip ${file} — not found`);
    continue;
  }

  // CSS goes just before </style> of the first style block.
  let next = upsertBlock(html, CSS_START, CSS_END, CSS, /<\/style>/);
  if (next === null) {
    console.log(`skip ${file} — no <style> block found`);
    continue;
  }
  // upsertBlock inserts AFTER the match, so for CSS move it before </style>.
  if (!html.includes(CSS_START)) {
    next = html.replace("</style>", `${CSS}\n</style>`);
  }

  // Nav goes right after the primary <nav>...</nav> in the masthead.
  const withNav = upsertBlock(
    next,
    START,
    END,
    navHtml(),
    /<nav class="nav"[\s\S]*?<\/nav>/
  );
  if (withNav === null) {
    console.log(`skip ${file} — no primary <nav class="nav"> found`);
    continue;
  }

  if (withNav !== html) {
    await fs.writeFile(p, withNav);
    console.log(`updated ${file}`);
    changed++;
  } else {
    console.log(`${file} already current`);
  }
}
console.log(`\n${changed} file(s) updated.`);
